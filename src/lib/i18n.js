export function useT() {
  const { state } = useStore()
  const lang = state.lang || 'en'
  const col = lang === 'hi' ? 1 : 0
  const t = (key, vars) => {
    let s = S[key] ? S[key][col] || S[key][0] : key
    if (vars) for (const k in vars) s = s.replaceAll(`{${k}}`, vars[k])
    return s
  }
  const L = (o) => (o ? (Array.isArray(o) ? o[col] || o[0] : o[lang] || o.en) : '')
  return { t, L, lang }
}
